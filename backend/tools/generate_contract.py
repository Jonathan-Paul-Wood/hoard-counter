"""Generate committed OpenAPI and TypeScript interfaces without Node tooling."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'backend'))
from whc.contract import specification


def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'anyOf' in schema:
        return ' | '.join(ts(value) for value in schema['anyOf'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    kind = schema.get('type')
    if kind == 'object':
        props = schema.get('properties', {})
        if not props:
            return 'Record<string, unknown>'
        return '{ ' + '; '.join(f'{key}{"" if key in schema.get("required", []) else "?"}: {ts(value)}' for key, value in props.items()) + ' }'
    if kind == 'array':
        return 'Array<' + ts(schema.get('items', {})) + '>'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


if __name__ == '__main__':
    spec = specification()
    (ROOT / 'openapi.json').write_text(json.dumps(spec, indent=2) + '\n', encoding='utf-8')
    output = '// Generated by backend/tools/generate_contract.py. Do not edit by hand.\n'
    output += '\n'.join(f'export type {name} = {ts(schema)};\n' for name, schema in spec['components']['schemas'].items())
    (ROOT / 'frontend' / 'lib' / 'generated.ts').write_text(output, encoding='utf-8')
